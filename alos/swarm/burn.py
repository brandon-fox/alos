"""Structured Markdown deliverable and optional git worktree executor for Spec 037 queue burn.

Spec: specs/037-backlog-staging-and-burn/spec.md (FR-3705, FR-3706)
ADR: ADR-0025 (Multi-Repo Backlog Harvester, Active-Use Hold Latch, and Artifact Burn Executor)
"""

from __future__ import annotations

import contextlib
import json
import os
import re
import shutil
import subprocess  # nosec B404
import threading
from collections.abc import Callable
from datetime import datetime, timezone
from pathlib import Path
from typing import TYPE_CHECKING, Any

from alos.runtime import RuntimePaths
from alos.swarm.dispatcher import Ollama

if TYPE_CHECKING:
    from alos.swarm.queue import LeasedJob

BURN_WORKFLOWS = frozenset({"spec_audit", "issue_plan", "task_patch", "test_draft", "review_fix"})
SAFE_TOKEN_RE = re.compile(r"[^A-Za-z0-9._-]+")

WORKFLOW_INSTRUCTIONS: dict[str, str] = {
    "spec_audit": "Audit specification requirements, identify gaps, and output a checklist.",
    "issue_plan": "Produce a concrete TDD implementation plan and exact target file list.",
    "task_patch": "Draft the implementation plan, minimal diff patch, and verification commands.",
    "test_draft": "Write deterministic pytest unit/BDD tests targeting the acceptance criteria.",
    "review_fix": "Resolve the review finding with a root-cause fix and verification diff.",
}


def _safe_slug(raw: str) -> str:
    return SAFE_TOKEN_RE.sub("__", raw.strip()).strip("_") or "item"


def _compose_burn_prompt(job: LeasedJob) -> str:
    """Build a structured single-pass worker prompt from job metadata and payload."""
    instruction = WORKFLOW_INSTRUCTIONS.get(
        job.workflow_type, "Complete the engineering task with concrete, verifiable output."
    )
    title = str(job.payload.get("title") or job.job_id)
    source_ref = str(job.payload.get("source_ref") or "unspecified")
    body = str(job.payload.get("prompt") or job.payload.get("description") or title)
    return (
        f"Repository: {job.repo_slug}\n"
        f"Workflow: {job.workflow_type}\n"
        f"Source: {source_ref}\n"
        f"Task: {title}\n\n"
        f"Directive: {instruction}\n\n"
        f"Context:\n{body}\n"
    )


def _write_deliverable_files(
    paths: RuntimePaths, job: LeasedJob, gen_result: dict[str, Any]
) -> tuple[Path, Path]:
    """Persist per-job Markdown deliverable, vault Bus mirror, and append burn_digest.md."""
    safe_repo = _safe_slug(job.repo_slug)
    safe_id = _safe_slug(job.job_id)
    now_iso = datetime.now(timezone.utc).isoformat(timespec="seconds")
    title = str(job.payload.get("title") or job.job_id)
    source_ref = str(job.payload.get("source_ref") or "")
    model_used = str(gen_result.get("model", job.model_tier))
    eval_count = int(gen_result.get("eval_count") or 0)
    response_text = str(gen_result.get("response", "")).strip()
    raw_trace = gen_result.get("trace")
    trace: dict[str, Any] = raw_trace if isinstance(raw_trace, dict) else {}

    doc = (
        "---\n"
        f"job_id: {job.job_id}\n"
        f"repo_slug: {job.repo_slug}\n"
        f"workflow_type: {job.workflow_type}\n"
        f"model_tier: {job.model_tier}\n"
        f"model: {model_used}\n"
        f"source_ref: {source_ref}\n"
        f"completed_at: {now_iso}\n"
        f"tokens_out: {eval_count}\n"
        f"tokens_in: {int(trace.get('prompt_tokens') or 0)}\n"
        f"seconds: {round(float(trace.get('total_ms') or 0) / 1000.0, 1)}\n"
        "---\n\n"
        f"# {title}\n\n"
        "> Unreviewed local-model deliverable generated by ALOS StickyEpochQueue.\n\n"
        f"{response_text}\n"
    )
    out_dir = paths.results_dir / safe_repo
    out_dir.mkdir(parents=True, exist_ok=True)
    artifact_path = out_dir / f"{safe_id}.md"
    artifact_path.write_text(doc, encoding="utf-8")

    if paths.vault_dir.exists():
        bus_dir = paths.vault_dir / "Bus" / "Results"
        bus_dir.mkdir(parents=True, exist_ok=True)
        (bus_dir / f"{safe_id}.md").write_text(doc, encoding="utf-8")

    digest_path = paths.results_dir / "burn_digest.md"
    if not digest_path.exists():
        digest_path.write_text("# ALOS Queue Burn Digest\n\n", encoding="utf-8")
    digest_line = (
        f"- `{now_iso}` | **{job.repo_slug}** | `{job.job_id}` "
        f"(`{job.workflow_type}` / `{model_used}`): {title} -> `{artifact_path.name}`\n"
    )
    with digest_path.open("a", encoding="utf-8") as handle:
        handle.write(digest_line)
    return artifact_path, digest_path


def _clean_git_env() -> dict[str, str]:
    drop = {
        "GIT_DIR",
        "GIT_WORK_TREE",
        "GIT_INDEX_FILE",
        "GIT_COMMON_DIR",
        "GIT_OBJECT_DIRECTORY",
        "GIT_ALTERNATE_OBJECT_DIRECTORIES",
        "GIT_PREFIX",
    }
    return {k: v for k, v in os.environ.items() if k not in drop}


def _maybe_stage_worktree(
    paths: RuntimePaths, job: LeasedJob, artifact_path: Path
) -> dict[str, str]:
    """Create an isolated local git worktree draft branch when requested and valid."""
    if not job.payload.get("create_worktree_branch"):
        return {}
    raw_repo = str(job.payload.get("local_repo_path") or "").strip()
    git_bin = shutil.which("git")
    if not raw_repo or git_bin is None:
        return {}
    repo_path = Path(raw_repo).expanduser().resolve()
    if not (repo_path / ".git").exists():
        return {}

    safe_id = _safe_slug(job.job_id)
    branch = f"alos-burn/{safe_id}"
    wt_dir = paths.root / "worktrees" / safe_id
    wt_dir.parent.mkdir(parents=True, exist_ok=True)
    if not wt_dir.exists():
        cmd = [git_bin, "-C", str(repo_path), "worktree", "add", "-B", branch, str(wt_dir)]
        # Fixed argument vector invoking resolved git binary without shell expansion.
        res = subprocess.run(  # noqa: S603  # nosec B603
            cmd,
            env=_clean_git_env(),
            capture_output=True,
            text=True,
            timeout=30,
            check=False,
        )
        if res.returncode != 0:
            return {"worktree_error": (res.stderr or res.stdout).strip()[:240]}
    drafts_dir = wt_dir / ".alos_drafts"
    drafts_dir.mkdir(parents=True, exist_ok=True)
    (drafts_dir / f"{safe_id}.md").write_text(
        artifact_path.read_text(encoding="utf-8"), encoding="utf-8"
    )
    return {"worktree_branch": branch, "worktree_path": str(wt_dir)}


def _maybe_verify_in_sandbox(job: LeasedJob, artifact_path: Path) -> dict[str, Any]:
    """Run optional container sandbox check for test_draft workflows when requested."""
    if job.workflow_type != "test_draft" or not job.payload.get("verify_in_sandbox"):
        return {}
    raw_repo = str(job.payload.get("local_repo_path") or "").strip()
    if not raw_repo or not Path(raw_repo).is_dir():
        return {}
    from alos.swarm.sandbox import Limits, SandboxError, run_draft

    with contextlib.suppress(SandboxError, OSError):
        verdict = run_draft(Path(raw_repo), artifact_path, Limits())
        return {"sandbox_state": verdict.get("state"), "sandbox_passed": verdict.get("passed", 0)}
    return {}


def _append_generation_trace(paths: RuntimePaths, job: LeasedJob, result: dict[str, Any]) -> None:
    """Append one line per model call to ``ALOS_HOME/logs/generation_trace.jsonl``.

    Spec: specs/039-self-correcting-build-executor/spec.md (FR-3917)
    """
    trace = result.get("trace")
    if not isinstance(trace, dict):
        return
    record = {
        "at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "job_id": job.job_id,
        "repo_slug": job.repo_slug,
        "workflow_type": job.workflow_type,
        "model_tier": job.model_tier,
        "model": result.get("model"),
        "done_reason": result.get("done_reason"),
        "answer_chars": len(str(result.get("response") or "")),
        **trace,
    }
    paths.logs_dir.mkdir(parents=True, exist_ok=True)
    with (paths.logs_dir / "generation_trace.jsonl").open("a", encoding="utf-8") as handle:
        handle.write(json.dumps(record) + "\n")


def build_burn_executor(
    paths: RuntimePaths, mock_mode: bool = False
) -> Callable[[LeasedJob, Ollama, threading.Event], dict[str, Any]]:
    """Return a queue executor handling prompts and structured Spec 037 burn deliverables."""
    from dataclasses import replace

    from alos.swarm.queue import (
        EmptyResponseError,
        PreemptedExecutionError,
        default_prompt_executor,
        mock_prompt_executor,
    )

    def _traced(job: LeasedJob, client: Ollama, cancel_event: threading.Event) -> dict[str, Any]:
        """Run one real model call and trace it, including a call that fails empty."""
        try:
            result = default_prompt_executor(job, client, cancel_event)
        except EmptyResponseError as exc:
            failed = {"trace": exc.trace, "model": exc.model, "done_reason": "empty_answer"}
            _append_generation_trace(paths, job, failed)
            raise
        _append_generation_trace(paths, job, result)
        return result

    def _executor(job: LeasedJob, client: Ollama, cancel_event: threading.Event) -> dict[str, Any]:
        is_burn = job.workflow_type in BURN_WORKFLOWS or bool(job.payload.get("write_artifact"))
        if not is_burn:
            if mock_mode:
                return mock_prompt_executor(job, client, cancel_event)
            return _traced(job, client, cancel_event)

        if cancel_event.is_set():
            raise PreemptedExecutionError("cancelled before burn execution", job.checkpoint_ns)

        composed_prompt = _compose_burn_prompt(job)
        enriched_payload = {
            "max_tokens": 1800,
            "timeout_s": 180.0,
            **job.payload,
            "prompt": composed_prompt,
        }
        enriched_job = replace(job, payload=enriched_payload)
        if mock_mode:
            title = str(job.payload.get("title") or job.job_id)
            gen_res: dict[str, Any] = {
                "response": f"## Deliverable Summary\n\nTask: {title}\n\n- Plan & steps ready.",
                "model": f"mock:{job.model_tier}",
                "eval_count": 24,
                "done_reason": "stop",
            }
        else:
            gen_res = _traced(enriched_job, client, cancel_event)

        artifact_path, digest_path = _write_deliverable_files(paths, job, gen_res)
        wt_meta = _maybe_stage_worktree(paths, job, artifact_path)
        sb_meta = _maybe_verify_in_sandbox(job, artifact_path)
        return {
            **gen_res,
            "artifact_path": str(artifact_path),
            "digest_path": str(digest_path),
            **wt_meta,
            **sb_meta,
        }

    return _executor
